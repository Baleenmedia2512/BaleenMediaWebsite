        <h2>3. Slow Page Speed</h2>
        <p><strong>The Problem:</strong> Slow-loading pages frustrate users and earn you a ranking penalty.</p>
        <p><strong>Quick Fix:</strong> Compress images, minify CSS/JS, and enable GZIP on your server. Aim for a <strong>under-3-second</strong> load time.</p>

        <h2>4. Weak Internal Linking</h2>
        <p><strong>The Problem:</strong> If you don't link between related pages, Google can't crawl and index your content effectively.</p>
        <p><strong>Quick Fix:</strong> Within each article, link to 2-3 other relevant posts or service pages using descriptive anchor text.</p>

        <h2>5. No Mobile Optimization</h2>
        <p><strong>The Problem:</strong> Google now uses mobile-first indexing, so unresponsive designs tank your rankings.</p>
