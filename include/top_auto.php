<script>
// Perfect Mobile Navigation JavaScript
function menuFunction() {
    const mobileNavbar = document.getElementById('mobileNavbar');
    const mobileOverlay = document.getElementById('mobileOverlay');
    
    mobileNavbar.classList.add('show');
    mobileOverlay.classList.add('show');
    
    // Prevent body scroll when menu is open
    document.body.style.overflow = 'hidden';
}

function closeMobileMenu() {
    const mobileNavbar = document.getElementById('mobileNavbar');
    const mobileOverlay = document.getElementById('mobileOverlay');
    const servicesDropdown = document.getElementById('mobileServicesDropdown');
    const servicesToggle = document.getElementById('mobileServicesToggle');
    
    mobileNavbar.classList.remove('show');
    mobileOverlay.classList.remove('show');
    servicesDropdown.classList.remove('show');
    servicesToggle.classList.remove('active');
    
    // Restore body scroll
    document.body.style.overflow = 'auto';
}

function toggleMobileServices() {
    const servicesDropdown = document.getElementById('mobileServicesDropdown');
    const servicesToggle = document.getElementById('mobileServicesToggle');
    
    servicesDropdown.classList.toggle('show');
    servicesToggle.classList.toggle('active');
}

// Desktop service dropdown (keep existing functionality)
function myFunction() {
    if (window.innerWidth > 991.98) {
        document.getElementById("service").classList.toggle("show");
    }
}

// Initialize mobile navigation when page loads
document.addEventListener('DOMContentLoaded', function() {
    // Check if elements exist before adding event listeners
    const mobileNavClose = document.getElementById('mobileNavClose');
    const mobileOverlay = document.getElementById('mobileOverlay');
    const mobileServicesToggle = document.getElementById('mobileServicesToggle');
    
    if (mobileNavClose) {
        mobileNavClose.addEventListener('click', closeMobileMenu);
    }
    
    if (mobileOverlay) {
        mobileOverlay.addEventListener('click', closeMobileMenu);
    }
    
    if (mobileServicesToggle) {
        mobileServicesToggle.addEventListener('click', toggleMobileServices);
    }
    
    // Close mobile menu when clicking on menu links (except services)
    const mobileLinks = document.querySelectorAll('.mobile-nav-link');
    mobileLinks.forEach(link => {
        link.addEventListener('click', closeMobileMenu);
    });
    
    // Close mobile menu and navigate when clicking service items
    const serviceItems = document.querySelectorAll('.mobile-service-item');
    serviceItems.forEach(item => {
        item.addEventListener('click', closeMobileMenu);
    });
});

// Handle window resize
window.addEventListener('resize', function() {
    if (window.innerWidth > 991.98) {
        closeMobileMenu();
    }
});

// Close desktop dropdowns when clicking outside (desktop only)
window.onclick = function(event) {
    if (window.innerWidth > 991.98) {
        if (!event.target.matches('.nav-link')) {
            var dropdowns = document.getElementsByClassName("dropdown-menu");
            for (var i = 0; i < dropdowns.length; i++) {
                var openDropdown = dropdowns[i];
                if (openDropdown.classList.contains('show')) {
                    openDropdown.classList.remove('show');
                }
            }
        }
    }
}
</script>